def fmt(x, n=4):
    try:
        return f"{float(x):.{n}f}"
    except (TypeError, ValueError):
        return str(x)


def load(name):
    return json.loads((DATA / name).read_text())


def approval_errors(card):
    """No proxy, missing gate, or method-level win may authorize file bytes."""
    gates = card.get('promotion_gates', {})
    required = ('literal_registry_surface', 'literal_registry_final_dots',
                'full_registry_coverage', 'single_feature_canaries',
                'paired_fold_local_holdout_win', 'released_bytes_match_evaluated_method',
                'shared_evaluator_and_writer', 'budget_compliant', 'saved_byte_format',
                'separate_selector_approval')
    return [key for key in required if gates.get(key) is not True]


def main() -> int:
    from html import escape
    e = lambda x: escape(str(x), quote=True)
    card = json.loads((ROOT / 'evidence/gemsdoe_run_card.json').read_text())
    audit = json.loads((ROOT / 'evidence/focus_audit.json').read_text())
    errors = approval_errors(card)
    approved = card.get('verdict') == 'promote' and not errors
    if card.get('verdict') == 'promote' and errors:
        raise ValueError('Unsafe promotion: ' + ', '.join(errors))
    if approved:
        raise ValueError('Selector-approved publication requires a separately reviewed release renderer')
    decision = 'DO-NOT-SUBMIT'
    name = Path(card['download']['tif']).name
    src = ROOT / card['download']['tif']
    if hashlib.sha256(src.read_bytes()).hexdigest() != card['sha256']:
        raise ValueError('Research download hash mismatch')
    (DOCS / 'downloads').mkdir(exist_ok=True)
    for key in ('tif', 'zip'):
        p = ROOT / card['download'][key]
        shutil.copy2(p, DOCS / 'downloads' / p.name)
    hero = f'''<section class="hero no"><span class="tag no">DO NOT SUBMIT — research downloads only</span>
<h1>No file clears the requested protocol</h1><p>The earlier SUBMIT recommendation is withdrawn.
A proxy forecast is not an organizer score or HOLDOUT-DTI. The literal registry gate fails;
no weekly slot was used or selected by this review.</p>
<a class="btn alt" href="downloads/{e(name)}" download>Download existing research TIFF — NOT for submission</a>
<p class="small">{e(name)}<br>SHA-256 <code>{e(card['sha256'])}</code></p>
<p>Leaderboard estimate: <b>not defensibly estimable</b>. The archived ESTIMATE is unvalidated and is not a performance gate.</p></section>'''
    rows = []
    for r in audit['focus_sites']:
        comparisons = r.get('comparisons', [])
        duplicate = any(c.get('my_dots_within_3px', 0) > .70 for c in comparisons)
        rows.append(f'''<tr><td>{e(r['site'])}</td><td><a href="{e(r['download_research_only'])}">{e(r['filename'])}</a><small> — research only</small></td>
<td>{e(r['claimed_by_owner_not_receipt'])} (owner claim; unverified)</td><td>Not estimable</td>
<td>{'NO — protocol duplicate' if duplicate else 'Not established'}</td><td>NO — already scored; historical research only</td></tr>''')
    table = '''<h2>Nine-site executive summary</h2><p>Best historical file by the pinned owner ledger, not a current live ranking.
No submission-page receipt was available: none of these figures is ORGANIZER-CONFIRMED.
Protocol duplication is not the same as byte identity. All linked files are historical, not newly generated.</p>
<div style="overflow:auto"><table><tr><th>Site</th><th>Historical download</th><th>Historical owner claim</th>
<th>Leaderboard estimate</th><th>Unique under requested gate?</th><th>Submit?</th></tr>''' + ''.join(rows) + '''</table></div>'''
    why = '''<h2>Why GEMSDOE32 B2 may have helped</h2><p>The pinned raster audit finds B2 is a subset of GEMSDOE31 H27-4,
with 2,545 dots removed 1.41–2 pixels from the catalogue. Sparse placement and pruning can reduce redundant
false-positive mass under an asymmetric distance-tolerant metric. That is a plausible mechanism, not proof that pruning caused
the owner's reported result. Neither hidden truth nor a byte-linked upload receipt is available. A higher real result is possible,
but no defensible claim of beating the historical result follows from the local proxy.</p>
<p><a href="https://github.com/drivendataorg/gems-prize-reference-solution">Official organizer reference code</a> ·
<a href="https://www.drivendata.org/competitions/306/competition-doe-gems/page/967/">Official problem / format</a> ·
<a href="data/h6_1_proximity_pruning_holdout.json">Historical holdout evidence (not rerun)</a></p>'''
    guide = '''<h2>Exactly how submission works — only after approval</h2><ol>
<li>The automated system must pass all mandatory gates on the exact released TIFF. Current verdict: DO NOT SUBMIT.</li>
<li>A separate selector checks the live competition cap and authorizes a slot; this review does neither.</li>
<li>Only then download the approved single-band TIFF (or ZIP containing just that TIFF) and upload it on DrivenData's New submission form.</li>
<li>Use the recorded unique name and a note of at most 140 characters. Retain the organizer receipt and uploaded SHA-256.</li></ol>
<p>The previous range error cannot be diagnosed without the rejected bytes. The error was: "Predicted values must be in range [0, 1]". Validate all saved values as finite and in [0,1],
with CRS, shape and transform exactly matching the sample. Do not merely clip invalid data to conceal a pipeline defect.</p>'''
    blockers = '''<h2>Irregularities and limitations</h2><ul>
<li>The saved audit records a registered raster positive at every footprint cell: any nonempty in-footprint candidate has directed overlap 1.0 and fails the literal 0.70 gate. Dense/lattice exemptions require an explicit protocol revision, not an implementation convenience.</li>
<li>The skarpline approval substituted an SGMC proxy for the requested buffered hide-and-recover test, used a separate metric path, and its generator recorded exceeding the budget. The forecast is archived, not validated.</li>
<li>HCE-1's method-level holdout win does not clear its uniqueness-repaired final file. CSPES has a negative holdout. Neither is authorized by this review.</li>
<li>Data caches are absent in this checkout. GitHub mirrors establish byte identity, not organizer provenance. This session did not retrain or generate another TIFF.</li>
<li>Network policy permits GitHub and package registries, not DrivenData, USGS, Dropbox or NLR. Official page contents, live quota, current leaderboard and external-data availability were not verified here.</li>
<li>The prompt gives conflicting leaderboard targets. No current leaderboard maximum is asserted.</li></ul>'''
    research = '''<h2>Research queue, not execution approval</h2><p>The ranked hypotheses, layers, signatures, confounders and novelty limitations are recorded in
<a href="session-review.md">this session review</a>. No idea is claimed globally novel or execution-ready without source and data checks.
The target is surface fault geometry, not direct detection of geothermal vents.</p>'''
    bodies = {'index.html': hero + table + why,
              'executive-summary.html': hero + table + guide + why,
              'research.html': hero + research + why + blockers,
              'evidence.html': hero + blockers + '<p><a href="data/run_card.json">Decision card</a> · <a href="data/focus_audit.json">Pinned raster audit</a> · <a href="session-review.md">Three-pass review and next steps</a></p>'}
    for filename, body in bodies.items():
        (DOCS / filename).write_text(page(filename.split('.')[0], body, decision, filename))
    for dest in ('run_card.json', 'gemsdoe_run_card.json'):
        (DATA / dest).write_text(json.dumps(card, indent=2) + '\n')
    shutil.copy2(ROOT / 'evidence/focus_audit.json', DATA / 'focus_audit.json')
    download_body = ( hero.replace('href="downloads/', 'href="') + '\n<h2>Research only</h2><p>All historical and parallel artifacts are not cleared by this review. <a href="../cspes/index.html">CSPES lane</a></p>' + '\n' + '\n'.join('<p><code>' + e(p.name) + '</code></p>' for p in sorted((DOCS / 'downloads').glob('*.tif')) if p.name != name))
    (DOCS / 'downloads/index.html').write_text('<!doctype html><html lang="en"><head><meta charset="utf-8"><title>Research downloads</title><style>' + CSS + '</style></head><body><main>' + download_body + '<p><a href="../executive-summary.html">Executive summary</a></p></main></body></html>')
    (DOCS / 'downloads/LEGACY-DO-NOT-SUBMIT.txt').write_text('DO NOT SUBMIT. All TIFFs here are research-only under the current protocol. See ../executive-summary.html.\n')
    print('Site rebuilt: DO-NOT-SUBMIT; historical artifacts preserved; no slot used.')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
