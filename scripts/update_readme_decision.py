#!/usr/bin/env python3
"""Render the README decision block and nine-site table from evidence JSONs (idempotent).

Replaces the text between <!-- DECISION:START --> / <!-- DECISION:END --> and
<!-- FOCUS9:START --> / <!-- FOCUS9:END -->; on first run it replaces the legacy
banner (everything before the first '## ' heading) and the legacy nine-site
section, and marks superseded legacy sections.  No number is typed by hand.
"""
from __future__ import annotations

import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
EV = ROOT / "evidence"
SUPERSEDED = ("> **SUPERSEDED 2026-10-27 (LBCAL session).** The SUBMIT claim and the 0.428 ESTIMATE in this "
              "historical section are withdrawn. The current decision is at the top of this README and in "
              "[`evidence/decision.json`](evidence/decision.json).\n")
LEGACY_HEADINGS = ("## Why GEMSDOE32's 0.2778 won, and why it is beatable", "## Results and limitations of this session",
                   "## Reproduce the submission and the site", "## Remaining work and known limitations",
                   "## Parallel lane LST1", "## Peer-preserved historical owner brief")


def f(x, n=4):
    return f"{float(x):.{n}f}"


def decision_block() -> str:
    d = json.loads((EV / "decision.json").read_text())
    lb = json.loads((EV / "lbcal_run_card.json").read_text())
    conc = json.loads((EV / "lbcal_gate_concordance.json").read_text())
    var = json.loads((EV / "lbcal_variants.json").read_text())
    v = var["variants"][var["selected"]]
    c = json.loads((EV / "candidates_2026-10-27.json").read_text())
    snap = json.loads((EV / "leaderboard_snapshot_2026-10-27T1905Z.json").read_text())
    post = lb.get("post_hoc_diagnostics", {})
    sk = next(x for x in c["this_repo"] if "skarpline" in x["file"])
    hc = next(x for x in c["this_repo"] if "hce1" in x["file"])
    tif = Path(lb["file"]["path"]).name
    return f"""<!-- DECISION:START -->
# WBGGEMSDOE3: DOE GEMS Prize fault-mapping research, with one reconciled decision

> **CURRENT DECISION: DO NOT SUBMIT.** No file in this repository passes every automated gate
> ([`evidence/decision.json`](evidence/decision.json); generated by `scripts/reconcile_decision.py`).
>
> * **Withdrawn:** the earlier SUBMIT banner for `wbggemsdoe3-skarpline-union`. Its 0.428 figure was an ESTIMATE
>   fitted to 11 near-duplicate files. The leaderboard-calibrated model below estimates **{f(sk['lbcal_estimate'],3)}**.
> * **Newest lane: LBCAL** (leaderboard-calibrated hidden-fault density). It produced a unique-by-construction,
>   format-valid TIFF with {lb['file']['dots']:,} dots
>   ([research download, DO NOT SUBMIT](docs/downloads/{tif}), SHA-256 `{lb['file']['sha256'][:16]}…`).
>   Its cross-fit **ESTIMATE is {f(est := lb['estimate']['cross_fit_mean'],3)}** (bootstrap
>   {f(lb['estimate']['family_bootstrap_95'][0],3)}–{f(lb['estimate']['family_bootstrap_95'][1],3)}; heuristic neighbour-adjusted range
>   {f(post.get('worst_case_ratio_adjusted_estimate', 0),2)}–{f(est * post.get('nn_max_ratio', 1),2)}). That is a model output, **not an organizer score**.
>   It is **NEGATIVE** under the owner's pre-registered rules for two reasons:
>   1. HOLDOUT-DTI is **{f(lb['holdout']['pooled_dti'])}** (95% CI {f(lb['holdout']['ci95'][0])}–{f(lb['holdout']['ci95'][1])},
>      {lb['holdout']['evaluator']}, {lb['holdout']['n_withheld']:,} withheld), below the holdout best of {f(lb['holdout']['current_best']['pooled_dti'])}.
>   2. 81–91% of its dots fall inside the 3 px halos of four dense registry rasters: h23-a, h23-b, h30 and ovtr.
> * **HCE-1** (parallel lane) is downloadable for research. Its released file's static HOLDOUT-DTI is 0.0931, its
>   uniqueness pass depends on the disputed IR-09 reading, and its LBCAL ESTIMATE is {f(hc['lbcal_estimate'],3)}. It is not cleared for a slot.
> * **Key science result:** LBCAL predicts held-out families' public scores with Spearman
>   **{f(v['family_cv']['spearman'],2)}** (RMSE {f(v['family_cv']['rmse'],3)}; n={conc['n']}). The owner's holdout gate correlates with the same
>   scores at **ρ = {f(conc['spearman_holdout_vs_score'],2)}**. The gate cannot see the leaderboard; whether to change it is the owner's decision.
> * Public leaderboard ({snap['observed_utc']}): #1 {snap['rows'][0]['public_dti']}, top-5 cut-off {snap['rows'][4]['public_dti']}.
>   The best owner-reported file here (GEMSDOE32 B2, 0.2778) is below rank #48. No weekly slot was used.
>
> **Site with the decision, executive summary and how-to-submit page:** <https://wingbangboozle1-lang.github.io/WBGGEMSDOE3/>
> ([start](docs/index.html) · [executive summary](docs/executive-summary.html) · [how to submit](docs/how-to-submit.html) ·
> [science](docs/research.html) · [evidence](docs/evidence.html) · [data & sources](docs/sources.html)).
> LBCAL artefacts: [run card](evidence/lbcal_run_card.json) · [CV](evidence/lbcal_cv.json) ·
> [variants](evidence/lbcal_variants.json) · [gate concordance](evidence/lbcal_gate_concordance.json) ·
> [pre-registration and hypotheses](knowledge/preregistration-2026-10-27-lbcal.md) · [findings](knowledge/lbcal-findings-2026-10-27.md).
>
> The full standing brief is preserved in [PROJECT_PROMPT.md](PROJECT_PROMPT.md). Read it and this README at every session start.
<!-- DECISION:END -->
"""


def focus_block() -> str:
    fs = json.loads((EV / "focus_sites_2026-10-27.json").read_text())
    rows = ["| Site | Best file (download) | Owner-reported | LBCAL ESTIMATE (family-CV) | Unique vs other focus sites? | OK to submit? |",
            "|---|---|---|---|---|---|"]
    for s in fs["sites"]:
        link = f"[`{s['file']}`]({s['download_url']})" if s["download_url"] else f"`{s['file']}`"
        rows.append(f"| {s['site']} | {link} | {s['owner_reported']} | {f(s['lbcal_family_cv_estimate'],3)} | "
                    f"NO ({f(s['max_forward_overlap_vs_other_focus']*100,1)}% of dots within 3 px of {s['max_overlap_with']}) | NO (already scored) |")
    best = max(fs["sites"], key=lambda s: s["owner_reported"])
    return ("<!-- FOCUS9:START -->\n## The nine focus sites, in one table (regenerated 2026-10-27)\n\n"
            f"Best overall: **{best['site']} `{best['file']}` ({best['owner_reported']}, OWNER-REPORTED)**. All nine best files are the\n"
            "same d2.8 dotted-ridge lineage. None is unique against the others, and none should be resubmitted.\n"
            "Source: [`evidence/focus_sites_2026-10-27.json`](evidence/focus_sites_2026-10-27.json).\n\n"
            + "\n".join(rows) + "\n<!-- FOCUS9:END -->\n")


def main() -> int:
    p = ROOT / "README.md"
    s = p.read_text()
    if "<!-- DECISION:START -->" in s:
        s = re.sub(r"<!-- DECISION:START -->.*?<!-- DECISION:END -->\n", decision_block(), s, flags=re.S)
    else:
        first = s.index("\n## ")
        s = decision_block() + s[first:]
    if "<!-- FOCUS9:START -->" in s:
        s = re.sub(r"<!-- FOCUS9:START -->.*?<!-- FOCUS9:END -->\n", focus_block(), s, flags=re.S)
    else:
        a = s.index("## The nine focus sites, in one table")
        b = s.index("\n## ", a + 5) + 1
        s = s[:a] + focus_block() + "\n" + s[b:]
    for h in LEGACY_HEADINGS:
        i = s.find(h)
        if i < 0:
            continue
        j = s.index("\n", i) + 1
        if not s[j:].lstrip("\n").startswith("> **SUPERSEDED 2026-10-27"):
            s = s[:j] + "\n" + SUPERSEDED + s[j:]
    p.write_text(s)
    print("README decision block and nine-site table rendered")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
