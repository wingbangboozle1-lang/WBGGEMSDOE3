#!/usr/bin/env python3
"""Deprecated entry point kept for the CI workflows and import compatibility.

The site is generated by ``scripts/build_executive.py`` from evidence JSON. This module
no longer renders pages; it delegates, and keeps ``human_age`` because older tests and the
freshness feed import it.
"""
from __future__ import annotations

from datetime import datetime
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def human_age(feed: dict) -> str:
    if not feed.get("last_success_utc"):
        return "No successful observation"
    try:
        datetime.fromisoformat(feed["last_success_utc"])
    except (ValueError, TypeError):
        return "Invalid observation timestamp"
    prefix = "Latest refresh failed · last success " if feed.get("last_attempt_error") else "Last checked · "
    return prefix + feed["last_success_utc"].replace("+00:00", " UTC")


def build() -> int:
    """Rebuild every page. Kept as a function for the legacy reproducibility test."""
    return subprocess.call([sys.executable, str(ROOT / "scripts" / "build_executive.py")])


def main() -> int:
    return build()


if __name__ == "__main__":
    raise SystemExit(main())
