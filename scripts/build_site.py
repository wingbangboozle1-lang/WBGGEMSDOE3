#!/usr/bin/env python3
"""Deprecated entry point kept for the CI workflows and import compatibility.

The site is generated by ``scripts/build_executive.py`` from evidence JSON. This module
no longer renders pages; it delegates, and keeps ``human_age`` because older tests and the
freshness feed import it.
"""
from __future__ import annotations

from datetime import datetime
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(Path(__file__).resolve().parent))

# The previous renderer is preserved verbatim as build_site_legacy so that the CSPES lane
# and the historical dashboards keep their helpers (overview, guide, historical_h6_section).
# None of its page writers are called any more: the four top-level pages are built by
# build_executive.py from evidence JSON.
from build_site_legacy import (  # noqa: E402,F401
    decision, esc, guide, historical_h6_section, human_age, layout, overview,
)

__all__ = ["build", "main", "human_age", "overview", "guide", "historical_h6_section"]


def build() -> int:
    """Rebuild every page. Kept as a function for the legacy reproducibility test."""
    return subprocess.call([sys.executable, str(ROOT / "scripts" / "build_executive.py")])


def main() -> int:
    return build()


if __name__ == "__main__":
    raise SystemExit(main())
